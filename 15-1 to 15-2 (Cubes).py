import matplotlib.pyplot as plt


x_values = list(range(1, 5000))
y_values = [x**3 for x in x_values]

plt.scatter(
    x_values,                  # X-координаты точек (последовательность чисел)
    y_values,                  # Y-координаты точек (последовательность чисел)
    s=20,                      # Размер маркеров (в точках^2). Может быть числом или массивом
    c=y_values,                # Цвет маркеров. Число, строка ('red'), RGB/RGBA или массив
    marker='s',                # Форма маркера: 'o' круг, 's' квадрат, '^' треугольник и т.д.
    cmap=plt.cm.Blues,         # Цветовая карта (используется только если c — массив чисел)
    norm=None,                 # Нормализация данных для cmap (объект Normalize)
    vmin=None,                 # Минимальное значение для цветовой шкалы (переопределяет norm)
    vmax=None,                 # Максимальное значение для цветовой шкалы (переопределяет norm)
    alpha=0.7,                 # Прозрачность: 0 — полностью прозрачный, 1 — непрозрачный
    linewidths=1,              # Толщина контура маркера (в точках)
    edgecolors=None,        # Цвет контура маркера. 'face' — как заливка, 'none' — без контура
    plotnonfinite=False,       # Рисовать ли точки с NaN/inf значениями
    label='Кубы чисел',        # Подпись для легенды (используется с plt.legend())
    # --- Дополнительные свойства (передаются как **kwargs) ---
    # color='red',             # Альтернатива c: задаёт цвет одним значением
    # facecolors='green',      # Альтернатива c: цвет заливки маркера
    # zorder=2,                # Порядок отрисовки: больше число — выше слой
    # picker=5,                # Радиус в пикселях для выбора точки мышью (события)
    # url='https://...',       # URL, привязанный к точке (для интерактивных бэкендов)
    # gid='my_group',          # Идентификатор группы для художника (Artist)
    # rasterized=False,        # Растеризовать ли точки в изображение (для PDF/SVG)
    # clip_on=True,            # Обрезать ли маркеры по границам осей
    # visible=True,            # Отображать ли точки на графике
)


plt.show()

